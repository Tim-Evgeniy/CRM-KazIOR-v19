"""Shared category prompts. Placeholders request facts; they never assert a repair."""
CATEGORIES={
 'Компьютер':('Компьютер / инвентарный номер','Что происходит при включении','Сообщение на экране'),
 'Принтер':('Модель принтера','Что происходит при печати','Ошибка или индикатор на принтере'),
 'Сеть':('Не открывается сайт или нет всей сети','Подключение по кабелю','Есть ли проблема у коллег'),
 'Wi-Fi':('Название сети Wi-Fi','Устройство','Не видит сеть, не подключается или нет интернета'),
 'Видеонаблюдение':('Камера / место установки','Нет изображения или записи','Когда заметили проблему'),
 'Сервер':('Название сервиса / сервера','Что стало недоступно','Какие сотрудники затронуты'),
 'ПО / МИС':('Название программы / МИС','Действие перед ошибкой','Точный текст ошибки без данных пациентов'),
 'Телефония':('Внутренний номер телефона','Не проходят входящие или исходящие звонки','Есть ли гудок / сообщение'),
 'СКС':('Номер розетки / порта, если известен','Место повреждения или отсутствие подключения','Какие устройства подключены'),
 'Другое':('Что нужно сделать','Что происходит сейчас','Какого результата ожидаете')}

def create_draft(c):
 category=c.get('category') if c.get('category') in CATEGORIES else 'Другое'
 text=['Здравствуйте.',f"Категория: {category}."]
 if c.get('subject'):text.append('Проблема: '+c['subject'].strip().rstrip('.')+'.')
 if c.get('draft'):
  draft=c['draft'].strip();text.append(draft[:1].upper()+draft[1:])
 location=', '.join(x for x in (c.get('dept'),('кабинет '+c['room']) if c.get('room') else '',c.get('location')) if x)
 text.append('Место: '+(location or '[укажите отделение и кабинет]')+'.')
 if not c.get('draft'):
  text.extend(q+': [уточните, если известно].' for q in CATEGORIES[category])
  text.append('Когда началось: [укажите время].')
 text.append('Прошу помочь с решением. При необходимости готов(а) уточнить подробности.')
 return '\n'.join(text)

